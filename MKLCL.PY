# Generates the LCL-named alias units (LCL/*.PAS) from the TUI units.
import re, os, sys
SRC = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(SRC, 'LCL')

def interface(unit):
    t = open(os.path.join(SRC, unit.upper() + '.PAS'), encoding='latin-1').read()
    i = t.lower().index('\nimplementation')
    t = t[:i]
    t = re.sub(r'\{[^}]*\}', '', t)          # comments
    t = re.sub(r'//[^\n]*', '', t)
    return t

cache = {}
def iface(unit):
    if unit not in cache: cache[unit] = interface(unit)
    return cache[unit]

def section_at(text, pos):
    best = None
    for m in re.finditer(r'(?im)^ ?(type|const|var|resourcestring)\b', text):
        if m.start() <= pos: best = m.group(1).lower()
        else: break
    return best

def find(unit, name):
    t = iface(unit)
    # routines
    rs = []
    for m in re.finditer(r'(?im)^\s*(function|procedure)\s+' + name + r'\b', t):
        # up to the ';' that ends the header (after the parameters / result)
        s = m.start()
        depth = 0; i = m.end()
        while i < len(t):
            c = t[i]
            if c == '(': depth += 1
            elif c == ')': depth -= 1
            elif c == ';' and depth == 0: break
            i += 1
        hdr = t[s:i+1].strip()
        # directives such as overload;
        rest = t[i+1:i+40]
        rs.append(re.sub(r'\s+', ' ', hdr))
    if rs: return ('routine', rs)
    m = re.search(r'(?<![\w.])' + name + r'\s*=', t)
    if m:
        sec = section_at(t, m.start())
        after = t[m.end():].lstrip()
        if sec == 'const': return ('const', None)
        if after.startswith('('):
            body = after[1:after.index(')')]
            members = [x.strip() for x in body.split(',') if x.strip()]
            return ('enum', members)
        return ('type', None)
    m = re.search(r'(?<![\w.])' + name + r'\s*:\s*([\w.]+)', t)
    if m and section_at(t, m.start()) == 'var':
        return ('var', m.group(1))
    raise Exception('not found: %s in %s' % (name, unit))

def params(hdr):
    m = re.search(r'\((.*)\)', hdr)
    if not m: return []
    names = []
    for grp in m.group(1).split(';'):
        grp = grp.strip()
        if not grp: continue
        left = grp.split(':')[0]
        left = re.sub(r'^\s*(const|var|out|constref)\s+', '', left)
        names += [x.strip() for x in left.split(',')]
    return names

def gen(lcl, uses, items, extra_types='', doc=''):
    types, consts, vars_, routines = [], [], [], []
    seen = set()
    for unit, name in items:
        if name in seen: continue
        seen.add(name)
        kind, info = find(unit, name)
        if kind == 'type':
            types.append('   %s = %s.%s;' % (name, unit, name))
        elif kind == 'enum':
            types.append('   %s = %s.%s;' % (name, unit, name))
            for mbr in info:
                consts.append('   %s = %s.%s;' % (mbr, unit, mbr))
        elif kind == 'const':
            consts.append('   %s = %s.%s;' % (name, unit, name))
        elif kind == 'var':
            vars_.append('   %s: %s absolute %s.%s;' % (name, info, unit, name))
        elif kind == 'routine':
            ov = len(info) > 1
            for h in info:
                h2 = h.rstrip(';') + ';'
                if ov and 'overload' not in h2: h2 += ' overload;'
                routines.append((unit, name, h2))
    L = []
    L.append('{ %s - generated by MKLCL.PY: the LCL unit name for the TUI units. }' % lcl)
    if doc: L.append('{ %s }' % doc)
    L.append('unit %s;' % lcl)
    L.append('')
    L.append('{$mode objfpc}{$H+}')
    L.append('')
    L.append('interface')
    L.append('')
    L.append('uses %s;' % ', '.join(uses))
    L.append('')
    if types or extra_types:
        L.append('type')
        L += types
        if extra_types: L.append(extra_types)
        L.append('')
    if consts:
        L.append('const')
        L += consts
        L.append('')
    if vars_:
        L.append('var')
        L += vars_
        L.append('')
    for u, n, h in routines:
        L.append(h)
    L.append('')
    L.append('implementation')
    L.append('')
    for u, n, h in routines:
        decl = re.sub(r'\s*overload;', '', h)
        L.append(decl)
        L.append('begin')
        args = ', '.join(params(h))
        call = '%s.%s' % (u, n) + ('(%s)' % args if args else '')
        if h.lower().startswith('function'): L.append('   Result := %s;' % call)
        else: L.append('   %s;' % call)
        L.append('end;')
        L.append('')
    L.append('end.')
    open(os.path.join(OUT, lcl.upper() + '.PAS'), 'w', encoding='latin-1').write('\n'.join(L) + '\n')
    print('%-10s %d types, %d consts, %d vars, %d routines' % (lcl, len(types), len(consts), len(vars_), len(routines)))

